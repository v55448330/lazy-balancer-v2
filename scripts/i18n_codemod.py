#!/usr/bin/env python3
"""i18n 后端消息 codemod——extract(只读盘点) / apply(带 --write 与 dry-run 默认)。

批量编辑门禁遵守:①dry-run 默认,--write 才写盘;②逐文件报告命中数;
③只匹配单行精确模式 `Message: "<含中文>"` 与 `Message: <v>.Error()`;
④gin ctx 变量名按函数签名解析,解析失败即跳过并报告(宁漏勿错);
⑤幂等:已含 apimsg.T/apimsg.ErrMsg 的行跳过。

词条键按 Go 字面量**解码后**的原文哈希（key_of 消费解码文本）；
--catalog-out 的 JSON 值同为解码文本（转义由消费端负责）。
catalog_gen.go 由 `gencatalog <词条JSON> <en译文JSON>` 从 JSON 生成：
同键去重（内容分叉即报错）、键序稳定、Go 字面量转义单源 go_quote。
"""
import hashlib
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ZH = re.compile(r'Message: ("[^"]*[一-龥][^"]*")')
ERR = re.compile(r'Message: (\w+)\.Error\(\)')
FUNC = re.compile(r'func [^{]*?\((\w+) \*gin\.Context\)')
DONE = re.compile(r'apimsg\.(T|ErrMsg)\(')



def unquote_go(lit: str) -> str:
    """Go 双引号字面量 → 文本。本管线只处理 \\ 与 " 两种转义
    （codemod 匹配的 Message 字面量不含控制字符转义）。"""
    body = lit[1:-1]
    return body.replace('\\"', '"').replace("\\\\", "\\")


def go_quote(text: str) -> str:
    """文本 → Go 双引号字面量（生成 catalog_gen.go 的唯一转义点）。"""
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'

def key_of(zh: str) -> str:
    h = 0x811C9DC5
    for b in zh.encode("utf-8"):
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return "k_" + f"{h:08x}"


def scan(path):
    """返回 (sites, skipped) sites=[(lineno, ctxvar, kind, payload)]"""
    src = open(path, encoding="utf-8").read()
    lines = src.splitlines(keepends=True)
    func_at = {}  # 行号->ctx 变量名
    cur = None
    for i, ln in enumerate(lines):
        m = FUNC.search(ln)
        if m:
            cur = m.group(1)
        if cur:
            func_at[i] = cur
    sites, skipped = [], []
    for i, ln in enumerate(lines):
        if DONE.search(ln):
            continue
        body = ln
        m = ZH.search(body)
        if m:
            zh = m.group(1)
            sites.append((i, func_at.get(i), "zh", zh))
            continue
        m = ERR.search(body)
        if m:
            sites.append((i, func_at.get(i), "err", m.group(1)))
    return sites, skipped


def apply_file(path, dry=True):
    src = open(path, encoding="utf-8").read()
    lines = src.splitlines(keepends=True)
    sites, _ = scan(path)
    catalog = {}
    changed = 0
    for lineno, ctxvar, kind, payload in sites:
        ln = lines[lineno]
        if ctxvar is None:
            print(f"  SKIP(no-ctx) {path}:{lineno+1}")
            continue
        indent = ln[: len(ln) - len(ln.lstrip())]
        if kind == "zh":
            text = unquote_go(payload)
            k = key_of(text)
            if k in catalog and catalog[k] != text:
                raise SystemExit(f"键冲突: {k} 对应两条不同文案（{path}:{lineno+1}）")
            catalog[k] = text
            new = ln.replace(
                f"Message: {payload}",
                f'Message: apimsg.T({ctxvar}, "{k}"), MessageKey: "{k}"',
            )
        else:
            new = ln.replace(
                f"Message: {payload}.Error()", f"Message: apimsg.ErrMsg({ctxvar}, {payload})"
            )
        lines[lineno] = new
        changed += 1
    if changed and not dry:
        body = "".join(lines)
        if '"lazy-balancer-v2/internal/apimsg"' not in body:
            body = body.replace(
                "import (", 'import (\n\t"lazy-balancer-v2/internal/apimsg"', 1
            )
            # gofmt 会排 import;此处先粗放,批量后统一 gofmt -w
        open(path, "w", encoding="utf-8").write(body)
    return changed, catalog


def gencatalog(zh_json, en_json, out_path, dry=True):
    """从解码文本 JSON 生成 catalog_gen.go：同键去重（分叉即报错）、
    键序稳定、转义单源 go_quote。dry-run 只报告不写盘。"""
    zh = json.load(open(zh_json, encoding="utf-8"))
    en = json.load(open(en_json, encoding="utf-8"))
    lines = [
        "// Code generated by i18n codemod; DO NOT EDIT.",
        "// zh 母本 + en 译文。",
        "",
        "package i18n",
        "",
        "func init() {",
    ]
    for k in sorted(zh):
        lines.append(f"\tRegister({go_quote(k)}, {go_quote(zh[k])}, {go_quote(en.get(k, ''))})")
    lines.append("}")
    body = "\n".join(lines) + "\n"
    print(f"gencatalog: {len(zh)} 键（去重后）, en 覆盖 {sum(1 for k in zh if en.get(k))} 键")
    if not dry:
        open(out_path, "w", encoding="utf-8").write(body)
        print(f"catalog_gen -> {out_path}")
    return len(zh)

def main():
    mode = sys.argv[1]
    paths = sys.argv[2:]
    if mode == "gencatalog":
        # 位置参数: <词条JSON> <en译文JSON> <输出go文件>；--write 才写盘。
        args = [a for a in paths if not a.startswith("--")]
        if len(args) != 3:
            raise SystemExit("用法: i18n_codemod.py gencatalog <词条JSON> <en译文JSON> <输出go文件> [--write]")
        gencatalog(args[0], args[1], args[2], dry="--write" not in sys.argv)
        return
    all_catalog = {}
    total = 0
    for p in paths:
        if not os.path.isfile(p):
            continue
        if mode == "extract":
            sites, _ = scan(p)
            for _, _, kind, payload in sites:
                if kind == "zh":
                    text = unquote_go(payload)
                    k = key_of(text)
                    if k in all_catalog and all_catalog[k] != text:
                        raise SystemExit(f"键冲突: {k} 对应两条不同文案（{p}）")
                    all_catalog[k] = text
                else:
                    all_catalog[f"__err__{payload}"] = payload
            print(f"{p}: {len(sites)}")
            total += len(sites)
        elif mode == "apply":
            n, cat = apply_file(p, dry="--write" not in sys.argv)
            all_catalog.update(cat)
            print(f"{p}: {n} 替换")
            total += n
    if mode == "apply" and "--catalog-out" in sys.argv:
        out = sys.argv[sys.argv.index("--catalog-out") + 1]
        json.dump(all_catalog, open(out, "w", encoding="utf-8"), ensure_ascii=False, indent=0, sort_keys=True)
        print(f"catalog -> {out} ({len(all_catalog)})")
    print(f"TOTAL: {total}")


if __name__ == "__main__":
    main()
